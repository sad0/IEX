"""Kit-limit test data (IEX feature kitLimit, docs/KIT_LIMIT.md): writes the WeiDU mod KitLimitTest.

  python -I tools/kitlimit/make_mod.py <out dir> [count=300]

The mod (install it after IEX, on a throwaway test game only) adds <count> single-class kits KLT001..KLTnnn with
IEX's helper (IEX/lib/iex_kits.tpa) and ADD_KIT_EX (IEX/lib/a7#add_kit_ex.tpa), so on a vanilla BG2EE (KITLIST rows
0..41) kit n lands on row 41 + n and kits 216 and up are past the engine's 256-row CLAB array.
Classes: n % 4 = 0 or 1 fighter, 2 mage, 3 thief.
CLAB of kit n: level 1 grants the innate K<nnn>L01. Probe kits (PROBE below) grant K<nnn>L<ll> at every level 1..30,
so the innates a creature knows tell exactly which CLAB levels the engine applied (and from which kit).
The innates are copies of SPCL211 (only their resref matters).
"""
import os
import sys

PROBE = {200, 208, 210, 215, 216, 217, 259, 260, 261, 262, 263, 280, 300}
LEVELS = 30
COLUMNS = 50


def kit_class(n):
    return (2, 2, 1, 4)[n % 4]


def clab(n):
    levels = range(1, LEVELS + 1) if n in PROBE else [1]
    head = ''.join('%-10d' % c for c in range(1, COLUMNS + 1))
    cells = ['GA_K%03dL%02d' % (n, c) if c in levels else '****' for c in range(1, COLUMNS + 1)]
    return '2DA V1.0\r\n****\r\n          %s\r\nABILITY1  %s\r\n' % (head, ''.join('%-10s ' % c for c in cells))


def main():
    out = os.path.join(sys.argv[1], 'KitLimitTest')
    count = int(sys.argv[2]) if len(sys.argv) > 2 else 300
    os.makedirs(os.path.join(out, 'clab'), exist_ok=True)
    for n in range(1, count + 1):
        with open(os.path.join(out, 'clab', 'KLC%03d.2DA' % n), 'w', newline='') as f:
            f.write(clab(n))
    spells = ['K%03dL%02d' % (n, l) for n in range(1, count + 1) for l in (range(1, LEVELS + 1) if n in PROBE else [1])]
    kits = '\r\n'.join(
        '  LAF ADD_KIT_EX INT_VAR kit_class = %d mixed = RESOLVE_STR_REF(~KLT%03d~) lower = RESOLVE_STR_REF(~klt%03d~)'
        ' help = RESOLVE_STR_REF(~KLT%03d: IEX kit limit test kit %d.~) prettify = 0 __kits_limit_override = iex_kit_limit'
        ' STR_VAR kit_name = ~KLT%03d~ clab_path = ~KitLimitTest/clab/KLC%03d.2DA~ RET kit_id END\r\n'
        '  OUTER_SET klt_row_%d = kit_id' % (kit_class(n), n, n, n, n, n, n, n)
        for n in range(1, count + 1))
    tp2 = f"""// IEX kit-limit test data, generated by tools/kitlimit/make_mod.py. Throwaway test games only.
BACKUP ~weidu_external/backup/KitLimitTest~
AUTHOR ~IEX tests~
VERSION ~v0.1~

BEGIN ~IEX kit limit test kits ({count} kits)~
REQUIRE_PREDICATE (MOD_IS_INSTALLED ~IEX/IEX.TP2~ ~0~) ~Install IEX first.~
INCLUDE ~IEX/lib/iex_kits.tpa~
INCLUDE ~IEX/lib/a7#add_kit_ex.tpa~
LAF iex_kit_limit RET iex_kit_limit = kit_limit END
PRINT ~kit limit for this game: %iex_kit_limit%~
ACTION_FOR_EACH klt_spl IN {' '.join(spells)} BEGIN
  COPY_EXISTING ~spcl211.spl~ ~override/%klt_spl%.spl~
END
{kits}
PRINT ~KLT001 row %klt_row_1%, KLT{count:03d} row %klt_row_{count}%~
"""
    with open(os.path.join(out, 'KitLimitTest.tp2'), 'w', newline='') as f:
        f.write(tp2.replace('\n', '\r\n').replace('\r\r\n', '\r\n'))
    print('wrote', out, count, 'kits,', len(spells), 'innates')


if __name__ == '__main__':
    main()
