"""Writes lua/IEX_EEexNames.lua: the EEex_* global names EEex defines at run time, as observed by the
differential test (the global.* cases of docs/DIFFTEST_<date>.json with an EEex result). Names only (API
surface), no behaviour. IEX_Missing.lua gives a stand-in only for these names; any other undefined EEex_* name
reads as nil, as under EEex.

Usage: python -I tools/difftest/eeex_names.py docs/DIFFTEST_<date>.json
"""
import json
import os
import sys

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
src = sys.argv[1]
d = json.load(open(src, encoding='utf-8'))
names = sorted({x['case'][7:] for x in d['cases'] if x['case'].startswith('global.EEex_')
                and x.get('eeex') and x['eeex'][0] in ('ok', 'err')})
lines = ['-- Generated by tools/difftest/eeex_names.py from %s: EEex_* globals defined under EEex (%d names).'
         % (os.path.basename(src), len(names)),
         '-- IEX_Missing.lua returns a stand-in only for these names when IEX does not define them.',
         'IEX_EEexNames = {']
row = ''
for n in names:
    item = "%s=1," % n
    if len(row) + len(item) > 116:
        lines.append('\t' + row.rstrip())
        row = ''
    row += item + ' '
if row:
    lines.append('\t' + row.rstrip())
lines.append('}')
open(os.path.join(REPO, 'lua', 'IEX_EEexNames.lua'), 'w', encoding='utf-8', newline='\n').write('\n'.join(lines) + '\n')
print(len(names), 'names')
