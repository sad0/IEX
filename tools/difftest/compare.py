"""Compares the probe results of the EEex and IEX runs (tools/difftest/run.ps1 writes them).

Usage: python -I compare.py <results dir> [--date YYYY-MM-DD]
Reads <dir>/eeex-run*.txt and <dir>/iex-run*.txt (one JSON object per line: {"case", "r" | "err"}), writes
docs/DIFFTEST_<date>.md and <dir>/difftest.json.

Classes: same / different / missing_in_iex / extra_in_iex / error_only_iex / error_only_eeex / different_error /
nondeterministic (the runs of one side disagree with each other).
"""
import glob
import json
import os
import re
import sys

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
ORDER = ['error_only_iex', 'missing_in_iex', 'different', 'different_error', 'error_only_eeex', 'extra_in_iex',
         'nondeterministic', 'cosmetic', 'same']
TITLES = {
    'error_only_iex': 'Error only in IEX', 'missing_in_iex': 'Missing in IEX (case absent)',
    'different': 'Different value', 'different_error': 'Both error, different message',
    'error_only_eeex': 'Error only in EEex', 'extra_in_iex': 'Only in IEX (absent under EEex)',
    'nondeterministic': 'Nondeterministic (runs of one side disagree)',
    'cosmetic': 'Cosmetic only (tostring of objects: userdata vs IEX class names / tables)', 'same': 'Same',
}


def norm_name(name):
    # event lines carry a global sequence number that shifts with unrelated events: key them by phase/name/#n
    return re.sub(r'^event\.\d+\.', 'event.', name)


def load_run(path):
    out = {}
    with open(path, encoding='utf-8', errors='replace') as f:
        for line in f:
            line = line.strip()
            if not line.startswith('{'):
                continue
            try:
                o = json.loads(line)
            except ValueError:
                continue
            name = norm_name(o.get('case', '?'))
            if 'skip' in o:
                out[name] = ('skip', o['skip'])
            elif 'err' in o:
                out[name] = ('err', o['err'])
            else:
                out[name] = ('ok', json.dumps(o.get('r'), sort_keys=True))
    return out


def side_runs(d, side):
    runs = [load_run(p) for p in sorted(glob.glob(os.path.join(d, side + '-run*.txt')))]
    return [r for r in runs if r]


def merged(runs):
    """case -> (kind, value, stable): stable is False when the runs disagree."""
    out = {}
    names = set().union(*runs) if runs else set()
    for n in names:
        vals = [r.get(n) for r in runs]
        first = next(v for v in vals if v is not None)
        stable = all(v == first for v in vals)
        out[n] = (first[0], first[1], stable)
    return out


OBJ = re.compile(r'(userdata|table|[A-Za-z_][A-Za-z0-9_]*)(: |@)<p>')


def cosmetic(v):
    """The value with object descriptions (tostring of userdata / tables) reduced to <obj>."""
    return OBJ.sub('<obj>', v).replace('{"__ud": "<obj>"}', '"<obj>"')


def classify(e, i):
    if e is None:
        return 'extra_in_iex'
    if i is None:
        return 'missing_in_iex'
    if not (e[2] and i[2]):
        return 'nondeterministic'
    if e[:2] == i[:2]:
        return 'same'
    if e[0] == i[0] == 'ok' and cosmetic(e[1]) == cosmetic(i[1]):
        return 'cosmetic'
    if e[0] == 'err' and i[0] == 'err':
        return 'different_error'
    if i[0] == 'err':
        return 'error_only_iex'
    if e[0] == 'err':
        return 'error_only_eeex'
    return 'different'


def group(name):
    head = name.split('.', 1)[0]
    if head in ('P0', 'P1', 'P2', 'P3', 'P4', 'P5'):
        return 'sprite'
    return head


def short(v, n=160):
    if v is None:
        return '(absent)'
    s = ('ERR ' if v[0] == 'err' else '') + v[1]
    s = s.replace('|', '\\|').replace('\n', ' ')
    return s if len(s) <= n else s[:n] + '...'


def main():
    d = sys.argv[1]
    date = os.path.basename(os.path.normpath(d))
    if '--date' in sys.argv:
        date = sys.argv[sys.argv.index('--date') + 1]
    eruns, iruns = side_runs(d, 'eeex'), side_runs(d, 'iex')
    if not eruns or not iruns:
        sys.exit('need at least one non-empty eeex-run*.txt and iex-run*.txt in %s' % d)
    E, I = merged(eruns), merged(iruns)
    rows = []
    for n in sorted(set(E) | set(I)):
        rows.append({'case': n, 'group': group(n), 'class': classify(E.get(n), I.get(n)),
                     'eeex': None if n not in E else list(E[n]), 'iex': None if n not in I else list(I[n])})
    counts = {c: sum(1 for r in rows if r['class'] == c) for c in ORDER}
    with open(os.path.join(d, 'difftest.json'), 'w', encoding='utf-8') as f:
        json.dump({'date': date, 'runs': {'eeex': len(eruns), 'iex': len(iruns)}, 'counts': counts, 'cases': rows},
                  f, indent=1)

    md = ['# Differential test EEex vs IEX, %s' % date, '',
          'Generated by `tools/difftest/compare.py` from `tools/difftest/run.ps1` (%d EEex run(s), %d IEX run(s), '
          'same game copy, save and probe). Every difference is an IEX bug to fix or an intended, documented '
          'improvement.' % (len(eruns), len(iruns)), '',
          '| Class | Cases |', '|---|---|']
    md += ['| %s | %d |' % (TITLES[c], counts[c]) for c in ORDER]
    md += ['| **Total** | %d |' % len(rows), '']
    notes = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'notes', 'DIFFTEST_%s.md' % date)
    if os.path.exists(notes):  # hand-written analysis of this run, kept above the generated tables
        with open(notes, encoding='utf-8') as f:
            md += [f.read().rstrip(), '']
    for c in ORDER:
        if c == 'same' or not counts[c]:
            continue
        md += ['## %s (%d)' % (TITLES[c], counts[c]), '']
        # EEex_* globals absent from IEX: names only (most are EEex internals no mod uses)
        names = [r['case'][7:] for r in rows if r['class'] == c and r['group'] == 'global' and c == 'missing_in_iex']
        if names:
            md += ['EEex globals absent from IEX (%d): %s' % (len(names), ', '.join('`%s`' % n for n in names)), '']
        md += ['| Case | EEex | IEX |', '|---|---|---|']
        for r in rows:
            if r['class'] == c and not (names and r['group'] == 'global'):
                e = tuple(r['eeex']) if r['eeex'] else None
                i = tuple(r['iex']) if r['iex'] else None
                md.append('| `%s` | %s | %s |' % (r['case'], short(e), short(i)))
        md.append('')
    os.makedirs(os.path.join(REPO, 'docs'), exist_ok=True)
    out = os.path.join(REPO, 'docs', 'DIFFTEST_%s.md' % date)
    with open(out, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(md) + '\n')
    print('compared %d cases -> %s' % (len(rows), out))
    for c in ORDER:
        print('  %-18s %d' % (c, counts[c]))


if __name__ == '__main__':
    main()
