"""Builds the probe files installed in a test copy's override (run with `python -I gen_cases.py <override dir>`).

- M_DIFFT.lua: probe/difft_body.lua wrapped in load(): a syntax or load-time error can never reach the engine
  (under EEex a Lua error in an M_ file opens a modal popup).
- M_DIFFTA.lua: DiffT_SurfaceNames (EEex names IEX lists in iex_api.json + names SadoEE uses) and
  DiffT_GeneratedCases (calls with literal arguments seen in real mods, from IEX-data/inventory/inventory.json
  when it exists).
- DIFFT.menu: the per-frame tick menu.
"""
import json
import os
import re
import shutil
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
API_JSON = r'E:/Dev/IEX-data/dist/iex_api.json'
INVENTORY = r'E:/Dev/IEX-data/inventory/inventory.json'
SADOEE_DIRS = [r'E:/Enhanced Edition/Environnement de test/EET 2.7.3 (dev)/PartyStash',
               r'E:/Enhanced Edition/Environnement de test/EET 2.7.3 (dev)/SadoQoL']


def wrap(src, chunk):
    level = 1
    while (']' + '=' * level + ']') in src:
        level += 1
    eq = '=' * level
    return ('-- Generated by tools/difftest/gen_cases.py: the code runs inside load() + pcall.\n'
            'local src = [' + eq + '[\n' + src + '\n]' + eq + ']\n'
            'local fn, err = (loadstring or load)(src, ' + json.dumps('=' + chunk) + ')\n'
            'local ok = fn ~= nil\n'
            'if fn then ok, err = pcall(fn) end\n'
            'if not ok then\n'
            '  pcall(function() local f = io.open("difftest_status.txt", "w") f:write("probe load error: " .. tostring(err) .. "\\n") f:close() end)\n'
            '  pcall(print, "DIFFT| probe load error: " .. tostring(err))\n'
            '  if IEX_Log then pcall(IEX_Log, "[DIFFT] probe load error: " .. tostring(err)) end\n'
            'end\n')


def surface_names():
    names = set()
    try:
        with open(API_JSON, encoding='utf-8') as f:
            names.update(n for n in json.load(f).get('eeex_names', []) if n.startswith('EEex_'))
    except OSError:
        pass
    for d in SADOEE_DIRS:
        for root, _, files in os.walk(d):
            for fn in files:
                if fn.lower().endswith(('.lua', '.menu', '.tpa', '.tph', '.tp2', '.d', '.baf')):
                    try:
                        with open(os.path.join(root, fn), encoding='utf-8', errors='replace') as f:
                            names.update(re.findall(r'\bEEex_[A-Za-z0-9_]*[A-Za-z0-9]', f.read()))
                    except OSError:
                        pass
    return sorted(names)


def lua_literal(v):
    if isinstance(v, bool):
        return 'true' if v else 'false'
    if isinstance(v, (int, float)):
        return repr(v)
    if isinstance(v, str):
        return json.dumps(v)  # JSON string escapes are valid Lua escapes for printable text
    return None


def inventory_cases():
    """Calls with only literal arguments, from the inventory (format tolerant: list or dict of items, each with a
    name and argument samples under 'calls' / 'args' / 'samples')."""
    if not os.path.exists(INVENTORY):
        return [], 'no inventory'
    try:
        with open(INVENTORY, encoding='utf-8') as f:
            inv = json.load(f)
    except (OSError, ValueError) as e:
        return [], 'inventory unreadable: %s' % e
    items = inv.get('items', inv) if isinstance(inv, dict) else inv
    if isinstance(items, dict):
        items = [dict(v, name=k) if isinstance(v, dict) else {'name': k} for k, v in items.items()]
    cases, seen = [], set()
    for it in items if isinstance(items, list) else []:
        if not isinstance(it, dict):
            continue
        name = it.get('name') or it.get('api')
        if not isinstance(name, str) or not re.match(r'^EEex_\w+$', name):
            continue
        samples = it.get('calls') or it.get('args') or it.get('samples') or []
        for s in samples if isinstance(samples, list) else []:
            args = s.get('args') if isinstance(s, dict) else s
            if not isinstance(args, list):
                continue
            lits = [lua_literal(a) for a in args]
            if any(x is None for x in lits) or len(lits) > 6:
                continue
            call = '%s(%s)' % (name, ', '.join(lits))
            if call in seen or len(cases) >= 400:
                continue
            seen.add(call)
            cases.append((call, 'function() return %s end' % call))
    return cases, 'inventory: %d literal calls' % len(cases)


def main():
    out = sys.argv[1]
    os.makedirs(out, exist_ok=True)
    with open(os.path.join(HERE, 'probe', 'difft_body.lua'), encoding='utf-8') as f:
        body = f.read()
    with open(os.path.join(out, 'M_DIFFT.lua'), 'w', encoding='utf-8', newline='\n') as f:
        f.write(wrap(body, 'M_DIFFT'))
    names = surface_names()
    cases, note = inventory_cases()
    lines = ['DiffT_SurfaceNames = {']
    lines += ['\t%s,' % json.dumps(n) for n in names]
    lines.append('}')
    # cases that crash the engine natively under EEex (run.ps1 adds them from the last TRACE line)
    skip_path = os.path.join(HERE, 'skip.txt')
    skips = []
    if os.path.exists(skip_path):
        with open(skip_path, encoding='utf-8') as f:
            skips = [l.strip() for l in f if l.strip() and not l.startswith('#')]
    lines.append('DiffT_Skip = {')
    lines += ['\t[%s] = true,' % json.dumps(s) for s in skips]
    lines.append('}')
    # focus run (run.ps1 -Focus): only these probe steps run, no cases
    focus = [s for s in os.environ.get('DIFFT_FOCUS', '').split(',') if s.strip()]
    lines.append('DiffT_Focus = {%s}' % ', '.join(json.dumps(s.strip()) for s in focus))
    lines.append('DiffT_GeneratedCases = {')
    for label, fn in cases:
        lines.append('\t{ %s, %s },' % (json.dumps(label), fn))
    lines.append('}')
    with open(os.path.join(out, 'M_DIFFTA.lua'), 'w', encoding='utf-8', newline='\n') as f:
        f.write(wrap('\n'.join(lines), 'M_DIFFTA'))
    shutil.copy(os.path.join(HERE, 'probe', 'DIFFT.menu'), os.path.join(out, 'DIFFT.menu'))
    print('probe installed in %s: %d surface names, %s' % (out, len(names), note))


if __name__ == '__main__':
    main()
